begin;

create table if not exists public.product_reviews (
  id uuid primary key default gen_random_uuid(),
  product_id text not null references public.products(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  order_item_id bigint references public.order_items(id) on delete set null,
  reviewer_name text not null,
  rating integer not null check (rating between 1 and 5),
  title text,
  content text not null,
  status text not null default 'pending' check (status in ('pending', 'published', 'rejected')),
  is_verified_purchase boolean not null default false,
  helpful_count integer not null default 0 check (helpful_count >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, product_id)
);
create index if not exists product_reviews_public_idx
  on public.product_reviews (product_id, status, created_at desc);

create table if not exists public.coupons (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  name text not null,
  description text,
  discount_type text not null check (discount_type in ('percentage', 'amount')),
  discount_value numeric(14, 2) not null check (discount_value > 0),
  minimum_order_value numeric(14, 2) not null default 0 check (minimum_order_value >= 0),
  maximum_discount numeric(14, 2) check (maximum_discount is null or maximum_discount > 0),
  usage_limit integer check (usage_limit is null or usage_limit > 0),
  used_count integer not null default 0 check (used_count >= 0),
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_at > starts_at),
  check (discount_type <> 'percentage' or discount_value <= 100)
);
create index if not exists coupons_active_idx on public.coupons (is_active, starts_at, ends_at);

create table if not exists public.coupon_redemptions (
  id bigint generated by default as identity primary key,
  coupon_id uuid not null references public.coupons(id) on delete restrict,
  order_id uuid not null unique references public.orders(id) on delete cascade,
  user_id uuid references auth.users(id) on delete set null,
  discount_amount numeric(14, 2) not null check (discount_amount >= 0),
  created_at timestamptz not null default now()
);
create index if not exists coupon_redemptions_coupon_idx on public.coupon_redemptions (coupon_id, created_at desc);
create index if not exists coupon_redemptions_user_idx on public.coupon_redemptions (user_id, created_at desc) where user_id is not null;

alter table public.orders add column if not exists coupon_code text;

alter table public.product_reviews enable row level security;
alter table public.coupons enable row level security;
alter table public.coupon_redemptions enable row level security;

drop policy if exists "product_reviews_public_read" on public.product_reviews;
create policy "product_reviews_public_read" on public.product_reviews for select to anon, authenticated
using (status = 'published');
drop policy if exists "product_reviews_owner_read" on public.product_reviews;
create policy "product_reviews_owner_read" on public.product_reviews for select to authenticated
using (user_id = auth.uid());
drop policy if exists "product_reviews_staff_read" on public.product_reviews;
create policy "product_reviews_staff_read" on public.product_reviews for select to authenticated
using (public.is_staff());

drop policy if exists "coupons_staff_read" on public.coupons;
create policy "coupons_staff_read" on public.coupons for select to authenticated
using (public.is_staff());
drop policy if exists "coupon_redemptions_staff_read" on public.coupon_redemptions;
create policy "coupon_redemptions_staff_read" on public.coupon_redemptions for select to authenticated
using (public.is_staff());
drop policy if exists "coupon_redemptions_owner_read" on public.coupon_redemptions;
create policy "coupon_redemptions_owner_read" on public.coupon_redemptions for select to authenticated
using (user_id = auth.uid());

revoke all on public.product_reviews, public.coupons, public.coupon_redemptions from anon, authenticated;
grant select on public.product_reviews to anon, authenticated;
grant select on public.coupons, public.coupon_redemptions to authenticated;

drop trigger if exists product_reviews_set_updated_at on public.product_reviews;
create trigger product_reviews_set_updated_at before update on public.product_reviews
