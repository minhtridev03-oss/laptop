create or replace function public.admin_update_payment_method(
  p_code text,
  p_display_name text,
  p_description text,
  p_config jsonb,
  p_is_active boolean
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_result public.payment_methods%rowtype;
begin
  if not public.is_staff() then raise exception 'FORBIDDEN'; end if;
  if jsonb_typeof(coalesce(p_config, '{}'::jsonb)) <> 'object' then raise exception 'INVALID_CONFIG'; end if;
  update public.payment_methods
  set display_name = btrim(p_display_name),
      description = nullif(btrim(coalesce(p_description, '')), ''),
      config = coalesce(p_config, '{}'::jsonb),
      is_active = p_is_active,
      updated_at = now()
  where code = p_code
  returning * into v_result;
  if not found then raise exception 'PAYMENT_METHOD_NOT_FOUND'; end if;
  return to_jsonb(v_result);
end;
$$;

revoke all on function public.admin_update_payment_method(text, text, text, jsonb, boolean) from public;
grant execute on function public.admin_update_payment_method(text, text, text, jsonb, boolean) to authenticated;

create or replace function public.admin_upsert_shipping_zone(p_zone jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_id uuid := nullif(p_zone->>'id', '')::uuid;
  v_result public.shipping_zones%rowtype;
begin
  if not public.is_staff() then raise exception 'FORBIDDEN'; end if;
  if v_id is null then v_id := gen_random_uuid(); end if;
  insert into public.shipping_zones (
    id, code, name, provinces, base_fee, free_shipping_threshold,
    estimated_days_min, estimated_days_max, is_active, sort_order
  ) values (
    v_id,
    btrim(p_zone->>'code'),
    btrim(p_zone->>'name'),
    coalesce(array(select jsonb_array_elements_text(coalesce(p_zone->'provinces', '[]'::jsonb))), '{}'::text[]),
    (p_zone->>'base_fee')::numeric,
    nullif(p_zone->>'free_shipping_threshold', '')::numeric,
    coalesce((p_zone->>'estimated_days_min')::integer, 1),
    coalesce((p_zone->>'estimated_days_max')::integer, 3),
    coalesce((p_zone->>'is_active')::boolean, true),
    coalesce((p_zone->>'sort_order')::integer, 0)
  )
  on conflict (id) do update set
    code = excluded.code,
    name = excluded.name,
    provinces = excluded.provinces,
    base_fee = excluded.base_fee,
    free_shipping_threshold = excluded.free_shipping_threshold,
    estimated_days_min = excluded.estimated_days_min,
    estimated_days_max = excluded.estimated_days_max,
    is_active = excluded.is_active,
    sort_order = excluded.sort_order,
    updated_at = now()
  returning * into v_result;
  return to_jsonb(v_result);
end;
$$;

revoke all on function public.admin_upsert_shipping_zone(jsonb) from public;
grant execute on function public.admin_upsert_shipping_zone(jsonb) to authenticated;

