create or replace function public.resolve_shipping_quote(
  p_province text,
  p_subtotal numeric
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_zone public.shipping_zones%rowtype;
  v_fee numeric(14, 2);
begin
  select * into v_zone
  from public.shipping_zones zone
  where zone.is_active = true
    and (
      cardinality(zone.provinces) = 0
      or exists (
        select 1 from unnest(zone.provinces) province
        where lower(unaccent(province)) = lower(unaccent(btrim(coalesce(p_province, ''))))
      )
    )
  order by case when cardinality(zone.provinces) > 0 then 0 else 1 end, zone.sort_order
  limit 1;

  if not found then raise exception 'SHIPPING_ZONE_NOT_FOUND'; end if;
  v_fee := case
    when v_zone.free_shipping_threshold is not null and p_subtotal >= v_zone.free_shipping_threshold then 0
    else v_zone.base_fee
  end;

  return jsonb_build_object(
    'zone_id', v_zone.id,
    'zone_code', v_zone.code,
    'zone_name', v_zone.name,
    'shipping_fee', v_fee,
    'free_shipping_threshold', v_zone.free_shipping_threshold,
    'estimated_days_min', v_zone.estimated_days_min,
    'estimated_days_max', v_zone.estimated_days_max
  );
end;
$$;

revoke all on function public.resolve_shipping_quote(text, numeric) from public;
grant execute on function public.resolve_shipping_quote(text, numeric) to anon, authenticated;

create or replace function public.get_checkout_configuration(
  p_province text,
  p_subtotal numeric
)
returns jsonb
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select jsonb_build_object(
    'shipping', public.resolve_shipping_quote(p_province, greatest(coalesce(p_subtotal, 0), 0)),
    'payment_methods', coalesce((
      select jsonb_agg(jsonb_build_object(
        'code', code,
        'display_name', display_name,
        'description', description,
        'config', config
      ) order by sort_order)
      from public.payment_methods
      where is_active = true
    ), '[]'::jsonb)
  );
$$;

revoke all on function public.get_checkout_configuration(text, numeric) from public;
grant execute on function public.get_checkout_configuration(text, numeric) to anon, authenticated;

-- Checkout facade: the inventory transaction stays isolated in
-- create_guest_order while this layer applies configurable fulfillment rules.
create or replace function public.create_checkout_order(
  p_customer jsonb,
  p_items jsonb,
  p_payment_method text default 'cod',
  p_notes text default null
) returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_result jsonb;
  v_order_id uuid;
  v_order public.orders%rowtype;
  v_quote jsonb;
  v_payment_config jsonb;
  v_shipping_fee numeric(14, 2);
  v_total numeric(14, 2);
begin
  select config into v_payment_config
  from public.payment_methods
  where code = p_payment_method and is_active = true;
  if not found then raise exception 'PAYMENT_METHOD_UNAVAILABLE'; end if;

  v_result := public.create_guest_order(p_customer, p_items, p_payment_method, p_notes);
  v_order_id := (v_result->>'order_id')::uuid;
  select * into v_order from public.orders where id = v_order_id for update;
  v_quote := public.resolve_shipping_quote(v_order.shipping_province, v_order.subtotal);
  v_shipping_fee := (v_quote->>'shipping_fee')::numeric;
  v_total := v_order.subtotal - v_order.discount_total + v_shipping_fee;

  update public.orders
  set shipping_zone_id = (v_quote->>'zone_id')::uuid,
      shipping_fee = v_shipping_fee,
      total = v_total,
      payment_reference = v_order.order_code,
      updated_at = now()
  where id = v_order_id;

  insert into public.notification_outbox (event_type, channel, recipient, order_id, payload)
  values (
    'order_created', 'internal', null, v_order_id,
    jsonb_build_object('order_code', v_order.order_code, 'total', v_total)
  );
  if v_order.customer_email is not null then
    insert into public.notification_outbox (event_type, channel, recipient, order_id, payload)
    values (
      'order_created', 'email', v_order.customer_email, v_order_id,
      jsonb_build_object('order_code', v_order.order_code, 'customer_name', v_order.customer_name, 'total', v_total)
    );
  end if;

  return v_result || jsonb_build_object(
    'shipping', v_quote,
    'shipping_fee', v_shipping_fee,
    'total', v_total,
    'payment_reference', v_order.order_code,
    'payment_config', v_payment_config
  );
end;
$$;

revoke all on function public.create_checkout_order(jsonb, jsonb, text, text) from public;
grant execute on function public.create_checkout_order(jsonb, jsonb, text, text) to anon, authenticated;
revoke execute on function public.create_guest_order(jsonb, jsonb, text, text) from anon, authenticated;

create or replace function public.queue_order_status_notification()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_order public.orders%rowtype;
begin
  select * into v_order from public.orders where id = new.order_id;
  insert into public.notification_outbox (event_type, channel, recipient, order_id, payload)
  values (
    'order_status_changed', 'internal', null, new.order_id,
    jsonb_build_object('order_code', v_order.order_code, 'from_status', new.from_status, 'to_status', new.to_status, 'note', new.note)
  );
  if v_order.customer_email is not null then
    insert into public.notification_outbox (event_type, channel, recipient, order_id, payload)
    values (
      'order_status_changed', 'email', v_order.customer_email, new.order_id,
      jsonb_build_object('order_code', v_order.order_code, 'customer_name', v_order.customer_name, 'from_status', new.from_status, 'to_status', new.to_status)
    );
  end if;
  return new;
end;
$$;

drop trigger if exists order_status_history_queue_notification on public.order_status_history;
